import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync('public/config.js','utf8'),context={window:{}};
vm.runInNewContext(source,context,{timeout:1000});
const base=context.window.APP_CONFIG||{};
const apiUrl=process.env.SO_LIEU_API_URL??base.apiUrl??'';
const sheetUrl=process.env.SO_LIEU_SHEET_URL??base.sheetUrl??'';
const valid=/^https:\/\/script\.google\.com\/macros\/s\/[A-Za-z0-9_-]+\/exec$/.test(apiUrl);
if((apiUrl||process.env.VERCEL)&&!valid)throw Error('Production requires SO_LIEU_API_URL (Apps Script /exec).');
if(sheetUrl&&!/^https:\/\/docs\.google\.com\/spreadsheets\/d\/[A-Za-z0-9_-]+/.test(sheetUrl))throw Error('SO_LIEU_SHEET_URL must be a Google Sheets HTTPS URL.');
fs.writeFileSync('dist/config.js','// Public configuration; never include credentials.\nwindow.APP_CONFIG = '+JSON.stringify({appName:base.appName||'Sổ Liệu',apiUrl,sheetUrl,currency:'VND'},null,2)+';\n');
console.log(valid?'Built live configuration.':'Built login page; configure Apps Script API before signing in.');
